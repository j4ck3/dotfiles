#!/bin/bash
# Software brightness + night light via Hyprland screen_shader.
# (hyprsunset CTM does not reach DRM on this AMD+LG setup — CTM blob stays empty.)
set -euo pipefail

STATE_FILE="${XDG_RUNTIME_DIR:-/tmp}/qs-display.state"
SLOT_FILE="${XDG_RUNTIME_DIR:-/tmp}/qs-display-slot"
LOCK_FILE="${XDG_RUNTIME_DIR:-/tmp}/qs-display.lock"
LOG_FILE="${XDG_RUNTIME_DIR:-/tmp}/qs-display-control.log"
SHADER_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/shaders"
SHADER_OFF="${SHADER_DIR}/qs-display-off.frag"
SHADER_A="${SHADER_DIR}/qs-display-a.frag"
SHADER_B="${SHADER_DIR}/qs-display-b.frag"
NIGHT_TEMP_DEFAULT=4500
GAMMA_MIN=10
GAMMA_MAX=100
TEMP_MIN=2500
TEMP_MAX=6500

log() {
  printf '%s %s\n' "$(date '+%H:%M:%S')" "$*" >>"$LOG_FILE" 2>/dev/null || true
}

usage() {
  echo "usage: $0 <gamma|temp|identity|toggle-night|gamma-delta> [value]" >&2
  exit 1
}

[[ $# -ge 1 ]] || usage
action=$1
value=${2:-}

# Serialize slider spam — concurrent writes caused empty .frag → EOF compile error.
exec 9>"$LOCK_FILE"
if ! flock -w 2 9; then
  log "lock timeout cmd=$action"
  exit 0
fi

load_state() {
  gamma=100
  temp=$TEMP_MAX
  identity=true
  night_temp=$NIGHT_TEMP_DEFAULT
  if [[ -f "$STATE_FILE" ]]; then
    # shellcheck disable=SC1090
    source "$STATE_FILE" 2>/dev/null || true
  fi
  gamma=${gamma:-100}
  temp=${temp:-$TEMP_MAX}
  identity=${identity:-true}
  night_temp=${night_temp:-$NIGHT_TEMP_DEFAULT}
}

save_state() {
  printf 'gamma=%s\ntemp=%s\nidentity=%s\nnight_temp=%s\n' \
    "$gamma" "$temp" "$identity" "$night_temp" >"$STATE_FILE"
}

clamp_int() {
  local n=$1 lo=$2 hi=$3
  if (( n < lo )); then n=$lo; fi
  if (( n > hi )); then n=$hi; fi
  printf '%s' "$n"
}

ensure_off_shader() {
  mkdir -p "$SHADER_DIR"
  if [[ ! -s "$SHADER_OFF" ]]; then
    cat >"$SHADER_OFF" <<'EOF'
#version 320 es
precision mediump float;
in vec2 v_texcoord;
layout(location = 0) out vec4 fragColor;
uniform sampler2D tex;
void main() { fragColor = texture(tex, v_texcoord); }
EOF
  fi
}

set_shader_path() {
  local path=$1
  # Never set screen_shader to "" — empty source → EOF error overlay.
  [[ -s "$path" ]] || {
    log "refusing empty shader path=$path"
    return 1
  }
  hyprctl eval "hl.config({ decoration = { screen_shader = \"${path}\" } })" >/dev/null
}

next_slot_path() {
  local slot=a
  if [[ -f "$SLOT_FILE" ]]; then
    slot=$(cat "$SLOT_FILE" 2>/dev/null || echo a)
  fi
  if [[ "$slot" == "a" ]]; then
    echo b >"$SLOT_FILE"
    printf '%s' "$SHADER_B"
  else
    echo a >"$SLOT_FILE"
    printf '%s' "$SHADER_A"
  fi
}

write_effect_shader() {
  local out=$1 bright=$2 warmth_temp=$3
  local tmp="${out}.tmp.$$"
  cat >"$tmp" <<EOF
#version 320 es
// Generated by display-control.sh — gamma=${gamma} temp=${warmth_temp} identity=${identity}
precision mediump float;
in vec2 v_texcoord;
layout(location = 0) out vec4 fragColor;
uniform sampler2D tex;

const float brightness = ${bright};
const float tempK = ${warmth_temp}.0;

void main() {
    vec4 c = texture(tex, v_texcoord);
    float warmth = clamp((6500.0 - tempK) / 4000.0, 0.0, 1.0);
    c.g *= mix(1.0, 0.78, warmth);
    c.b *= mix(1.0, 0.35, warmth);
    c.rgb *= clamp(brightness, 0.05, 1.5);
    fragColor = c;
}
EOF
  # Atomic replace so Hyprland never reads a truncated file.
  mv -f "$tmp" "$out"
  [[ -s "$out" ]] || return 1
}

apply_shader() {
  ensure_off_shader

  if [[ "$identity" == "true" ]] && (( gamma >= 100 )); then
    set_shader_path "$SHADER_OFF"
    log "shader passthrough (off)"
    return
  fi

  local bright warmth_temp path
  bright=$(awk -v g="$gamma" 'BEGIN { printf "%.4f", g / 100 }')
  if [[ "$identity" == "true" ]]; then
    warmth_temp=$TEMP_MAX
  else
    warmth_temp=$temp
  fi

  path=$(next_slot_path)
  write_effect_shader "$path" "$bright" "$warmth_temp"
  set_shader_path "$path"
  log "shader on path=$path gamma=$gamma temp=$warmth_temp identity=$identity"
}

load_state
log "cmd=$action value=${value:-}"

case "$action" in
  gamma)
    [[ -n "$value" ]] || usage
    gamma=$(clamp_int "${value%.*}" "$GAMMA_MIN" "$GAMMA_MAX")
    ;;
  gamma-delta)
    [[ -n "$value" ]] || usage
    gamma=$(clamp_int $((gamma + value)) "$GAMMA_MIN" "$GAMMA_MAX")
    ;;
  temp)
    [[ -n "$value" ]] || usage
    temp=$(clamp_int "${value%.*}" "$TEMP_MIN" "$TEMP_MAX")
    if (( temp >= TEMP_MAX )); then
      identity=true
      temp=$TEMP_MAX
    else
      identity=false
      night_temp=$temp
    fi
    ;;
  identity)
    identity=true
    temp=$TEMP_MAX
    ;;
  toggle-night)
    if [[ "$identity" == "true" ]]; then
      identity=false
      temp=$(clamp_int "$night_temp" "$TEMP_MIN" $((TEMP_MAX - 1)))
    else
      identity=true
      temp=$TEMP_MAX
    fi
    ;;
  *)
    usage
    ;;
esac

save_state
apply_shader
